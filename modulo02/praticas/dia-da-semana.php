<?php

$dia = "segunda";

switch ($dia) {
    case "domingo":
        echo "Domingo";
        break;

    case "segunda":
        echo "Segunda-feira";
        break;

    case "terça":
        echo "Terça-feira";
        break;
    case "quarta":
        echo "Quarta-feira";
        break;

    case "quinta":
        echo "Qunita-feira";
        break;

    case "sexta":
        echo "Sexta-feira";
        break;

    case "sabado":
        echo "Sá´bado";
        break;

        default:
        echo "Dia inválido";
}
